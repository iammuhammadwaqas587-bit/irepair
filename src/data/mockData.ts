export function calculateBuybackEstimate(
  modelId: string,
  storageSize: string,
  conditionId: BuybackConditionId
): { cash: number; storeCredit: number } {
  const model = BUYBACK_MODELS.find((m) => m.id === modelId) || BUYBACK_MODELS[0];
  const storage = model.storageOptions.find((s) => s.size === storageSize) || model.storageOptions[0];
  const condition = BUYBACK_CONDITIONS.find((c) => c.id === conditionId) || BUYBACK_CONDITIONS[0];

  const rawCash = (model.baseValuation + (storage ? storage.modifier : 0)) * condition.multiplier;
  const cash = Math.max(15, Math.round(rawCash));
  const storeCredit = Math.round(cash * 1.10); // +10% bonus for trade-in towards refurbished tech

  return { cash, storeCredit };
}

